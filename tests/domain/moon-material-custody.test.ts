/** Acquisition reducer component inputs only. These are not full-save fixtures,
 * natural continuations or substitutes for strict Moon source validation.
 * Every new bottle and receipt is generated by the real acquisition reducer.
 * Controlled check rolls and intervening body/budget inputs are explicit. */
function acquisitionOrigin(mode: 'SUPPLIER' | 'RECOVERY_SUPPLIER' | 'RECOVERY_PLAYER' | 'LATEST_FAILED' | 'RECOVERED_SUCCESS' = 'SUPPLIER', successOriginal: 1 | 2 | 3 = 2) {
  const s = readObjectEntry<SliceState>(sourcePath, 'final');
  const old = structuredClone(s.beautyGoddess); s.schemaVersion = 209; s.cash = 50000; s.actionsRemaining = 100;
  s.health = 100; s.mind = 100; s.spirituality = 120; s.seer.pollution = 0; s.injuries = []; s.injuryRisk = 0; s.revision += 2;
  const apply = (command: BeautyGoddessAcquisitionCommand, roll?: number) => {
    applyBeautyGoddessAcquisition(s, command, { note() {}, roll() { throw Error('No extra component draw'); }, check(ability, difficulty) {
      if (roll === undefined) throw Error('Only an explicit controlled consume has a check');
      s.random.cursor++; return resolveNormalCheck({ ability, baseAbility: s.character.coreStats[ability], difficulty, modifiers: [], roll });
    } }); s.revision++;
  };
  const recovery = (bottleId: string) => {
    apply({ type: 'REQUEST_RECOVERY_V1', bottleId }); s.week++; s.date = addGameWeeks(s.date, 1); s.revision += 2;
    apply({ type: 'RECOVER_CHARACTERISTIC_V1', bottleId }); return s.beautyGoddess.bottles.at(-1)!.id;
  };
  const consume = (bottleId: string, roll = 20) => {
    apply({ type: 'BUY_POTION', bottleId }); apply({ type: 'PREPARE_PROMOTION' }); apply({ type: 'CONSUME', bottleId, confirmed: true }, roll);
  };
  if (mode === 'SUPPLIER') {
    s.beautyGoddess = createBeautyGoddessState(); // Fresh acquisition-only branch, before any new receipt.
    apply({ type: 'LEARN_GUIDANCE' }); apply({ type: 'CONFIRM_TRANSFORMATION', confirmed: true });
    for (const taskId of BEAUTY_GODDESS_PREPARATION_IDS) apply({ type: 'PREPARE_TASK', taskId });
    apply({ type: 'POTION_WORK', bottleId: 'beauty-goddess-potion-2' });
    apply({ type: 'POTION_WORK', bottleId: 'beauty-goddess-potion-2' });
    consume('beauty-goddess-potion-1');
  } else {
    if (mode === 'RECOVERED_SUCCESS') consume(recovery(`beauty-goddess-potion-${successOriginal}`));
    else {
      const first = recovery('beauty-goddess-potion-1');
      if (mode === 'RECOVERY_PLAYER') apply({ type: 'BUY_POTION', bottleId: first });
      if (mode === 'LATEST_FAILED') consume(first, 80);
      const success = recovery('beauty-goddess-potion-2'); consume(success);
    }
    expect(s.beautyGoddess.bottles.slice(0, 3)).toEqual(old.bottles);
    expect(s.beautyGoddess.acquisitionJournal.slice(0, old.acquisitionJournal.length)).toEqual(old.acquisitionJournal);
  }
  const snapshot: Snapshot = { bottles: s.beautyGoddess.bottles, acquisitionJournal: s.beautyGoddess.acquisitionJournal, resupply: s.beautyGoddess.resupply };
  expect(resolveBeautyGoddessOriginalCharacteristicsSnapshot(snapshot)).not.toBeNull();
  return originOf(snapshot);
}

/** Explicit bounded host and six receipt IDs are module inputs only. The owned
 * engine must derive these from actual service journals; this never asserts a
 * whole save, source digest, renderer object or marker grants that authority. */
function materialsHost(origin = originOf(readComponent('success-original-1'))) {
  let state = createMoonMaterials(origin), revision = 2000;
  const host: MoonHost = { actorId: origin.actorId, eventId: 'material-2000', revision, week: 200, weekAnchor: 0,
    nowSecond: 0, location: MOON_HOME, verifiedReceipts: ['north-arrival', 'north-verify', 'reed-arrival', 'reed-verify', 'east-arrival', 'east-verify'],
    sequence: 1, status: 'ACTIVE', cash: 20000, actions: 3, health: 100, mind: 100, spirituality: 120, check: null };
  const move = (to: string) => { state = transportMoonMaterials(state, host.location, to); host.location = to; };
  const laterWeek = () => { host.week++; host.weekAnchor += 604800; host.nowSecond = host.weekAnchor; host.actions = 3; };
  const run = (command: MoonMaterialCommand) => {
    // Independent module resource host: replenish only by a declared later-week
    // input, with no wage grant or mutation of any historic acquisition receipt.
    if (host.actions < moonMaterialEffect(state, command).actions) laterWeek();
    host.eventId = `material-${revision}`; host.revision = revision++;
    const before = structuredClone(state), result = applyMoonMaterial(state, command, host);
    expect(state).toEqual(before); expect(result.effect.cashGain).toBe(0);
    expect([result.effect.health, result.effect.mind, result.effect.spirituality]).toEqual([0, 0, 0]);
    state = result.state; host.cash -= result.effect.cashCost; host.actions -= result.effect.actions; host.nowSecond += result.effect.seconds;
    return result;
  };
  const acquire = () => {
    move(MOON_SUPPLIER);
    for (const id of MOON_CHARACTERISTIC_BOTTLES) {
      const item = state.characteristics.find(c => c.originBottleId === id)!;
      if (item.holder === 'SUPPLIER') run({ type: 'ACQUIRE_CHARACTERISTIC', bottleId: id });
      else if (item.holder === 'UNLOCATED') { run({ type: 'INVESTIGATE_LEGACY_REMAINS', bottleId: id }); laterWeek(); run({ type: 'RECOVER_LEGACY_REMAINS', bottleId: id }); }
    }
    if (host.actions < 3) laterWeek();
    move(MOON_ARCHIVE); run({ type: 'VERIFY_UNIQUENESS', step: 'CHAIN' });
    move(MOON_VAULT); run({ type: 'VERIFY_UNIQUENESS', step: 'VACANCY' }); run({ type: 'ACQUIRE_UNIQUENESS' });
  };
  const compose = (batchId: MoonCarrierId = 'moon-carrier-1') => {
    move(MOON_SUPPLIER); run({ type: 'BUY_COMPOUND', batchId }); move(MOON_WORKSHOP); run({ type: 'COMPOSE_POTION', batchId });
  };
  const settle = (success: boolean, alive: boolean) => {
    const eventId = `consume-${revision++}`;
    state = settleMoonConsumption(state, { eventId, week: host.week, compoundId: state.compounds.at(-1)!.id, success, alive, location: host.location });
    return eventId;
  };
  return { host, get state() { return state; }, move, laterWeek, run, acquire, compose, settle };
}

